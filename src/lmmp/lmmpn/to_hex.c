mp_size_t lmmp_to_hex_len_(mp_srcptr numa, mp_size_t na) {
    if (numa) {
        do {
            if (na == 0)
                return 0;
        } while (numa[--na] == 0);
        // na 现为最高非零 limb 下标
        return (LIMB_BITS * na + lmmp_limb_bits_(numa[na]) + 3) >> 2;
    }
    return na << 4;
}

mp_size_t lmmp_to_hex_(char* dst, mp_srcptr numa, mp_size_t na, bool upper) {
    lmmp_param_assert(dst != NULL && numa != NULL);
    do {
        if (na == 0)
            return 0;
    } while (numa[--na] == 0);
    ++na;

    const uint16_t* ptab = upper ? lmmp_hex_pair_upper : lmmp_hex_pair_lower;
    mp_limb_t top = numa[na - 1];
    int bits = lmmp_limb_bits_(top);
    mp_size_t digits = (mp_size_t)((LIMB_BITS * (na - 1) + bits + 3) >> 2);

    char* wp = dst;
    for (mp_size_t i = 0; i < na - 1; ++i) {
        mp_limb_t l = numa[i];
        for (int j = 0; j < 8; ++j) {
            memcpy(wp, &ptab[l & 0xff], sizeof(uint16_t));
            wp += 2;
            l >>= 8;
        }
    }
    while (top >> 4) {  // 剩余至少 2 个 nibble
        memcpy(wp, &ptab[top & 0xff], sizeof(uint16_t));
        wp += 2;
        top >>= 8;
    }
    if (top)
        *wp++ = (char)ptab[top];

    return digits;
}
